import AppKit

struct ShelfItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text
        case paths(Int)
    }

    let id: String
    let kind: Kind
    let text: String

    var kindLabel: String {
        switch kind {
        case .text: return "文本 · \(text.count) 字"
        case .paths(let count): return count == 1 ? "文件路径" : "\(count) 个文件路径"
        }
    }

    func preview(limit: Int) -> String {
        switch kind {
        case .text:
            let flat = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            return flat.count > limit ? String(flat.prefix(limit)) + "…" : flat
        case .paths(let count):
            let names = text.split(separator: "\n").map { ($0 as NSString).lastPathComponent }
            let first = names.first ?? ""
            return count > 1 ? first + " 等 \(count) 个" : first
        }
    }
}

enum ShelfRejection: Error, Equatable {
    case empty, blank, sensitive, image, unsupported, tooLarge, full

    var message: String {
        switch self {
        case .empty: return "剪贴板是空的"
        case .blank: return "只有空白，没添加"
        case .sensitive: return "带有密码管理器的保密标记，没添加"
        case .image: return "图片和截图暂不支持"
        case .unsupported: return "这种内容暂不支持，只收文字和文件路径"
        case .tooLarge: return "超过 64KB，没添加"
        case .full: return "满了（5 条），先移除一条"
        }
    }
}

enum ShelfAddResult: Equatable {
    case added(String)
    case duplicate(String)
    case rejected(ShelfRejection)
}

enum ShelfCommand: Equatable {
    case add, copy(String), remove(String), clear(Set<String>)
}

struct ShelfNote: Equatable {
    enum Scope: Equatable {
        case shelf, item(String)
    }

    let text: String
    let scope: Scope
    let warning: Bool
}

struct Shelf: Equatable {
    static let limit = 5
    static let maxBytes = 64 * 1024
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    private(set) var items: [ShelfItem] = []
    private var nextNumber = 1

    func item(_ id: String) -> ShelfItem? {
        items.first { $0.id == id }
    }

    static func capture(_ pasteboard: NSPasteboard) -> Result<(ShelfItem.Kind, String), ShelfRejection> {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if types.isEmpty { return .failure(.empty) }
        if !types.isDisjoint(with: sensitiveTypes) { return .failure(.sensitive) }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .success((.paths(urls.count), urls.map(\.path).joined(separator: "\n")))
        }
        if let string = pasteboard.string(forType: .string) { return .success((.text, string)) }
        if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil) { return .failure(.image) }
        return .failure(.unsupported)
    }

    mutating func add(kind: ShelfItem.Kind, text: String) -> ShelfAddResult {
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .rejected(.blank) }
        if text.utf8.count > Self.maxBytes { return .rejected(.tooLarge) }
        if let existing = items.first(where: { $0.text == text }) { return .duplicate(existing.id) }
        if items.count >= Self.limit { return .rejected(.full) }
        let item = ShelfItem(id: "m\(nextNumber)", kind: kind, text: text)
        nextNumber += 1
        items.append(item)
        return .added(item.id)
    }

    mutating func add(from pasteboard: NSPasteboard) -> ShelfAddResult {
        switch Self.capture(pasteboard) {
        case .failure(let reason): return .rejected(reason)
        case .success(let captured): return add(kind: captured.0, text: captured.1)
        }
    }

    func copy(_ id: String, to pasteboard: NSPasteboard) -> Bool {
        guard let item = item(id) else { return false }
        pasteboard.clearContents()
        return pasteboard.setString(item.text, forType: .string)
    }

    @discardableResult
    mutating func remove(_ id: String) -> Bool {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return false }
        items.remove(at: index)
        return true
    }

    mutating func clear() {
        items.removeAll()
    }
}

extension AppModel {
    func shelfAction(_ command: ShelfCommand) {
        switch command {
        case .add:
            switch shelf.add(from: pasteboard) {
            case .added: showShelfNote(ShelfNote(text: "已添加", scope: .shelf, warning: false))
            case .duplicate: showShelfNote(ShelfNote(text: "已经有这一条了", scope: .shelf, warning: false))
            case .rejected(let reason): showShelfNote(ShelfNote(text: reason.message, scope: .shelf, warning: true))
            }
        case .copy(let id):
            guard shelf.item(id) != nil else {
                showShelfNote(ShelfNote(text: "这条材料已经不在了", scope: .shelf, warning: true))
                return
            }
            let copied = shelf.copy(id, to: pasteboard)
            showShelfNote(ShelfNote(text: copied ? "已复制，可以粘贴了" : "复制失败，请重试", scope: .item(id), warning: !copied))
        case .remove(let id):
            guard shelf.remove(id) else { return }
            showShelfNote(ShelfNote(text: "已移除一条", scope: .shelf, warning: false))
        case .clear(let ids):
            guard !shelf.items.isEmpty else { return }
            guard Set(shelf.items.map(\.id)) == ids else {
                showShelfNote(ShelfNote(text: "材料有变化，没清空，请重新确认", scope: .shelf, warning: true))
                return
            }
            shelf.clear()
            showShelfNote(ShelfNote(text: "已清空", scope: .shelf, warning: false))
        }
    }

    private func showShelfNote(_ note: ShelfNote) {
        shelfNote = note
        shelfNoteWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated {
                guard let self, self.shelfNote == note else { return }
                self.shelfNote = nil
                self.onUpdate?()
            }
        }
        shelfNoteWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 8, execute: work)
        onUpdate?()
    }
}
